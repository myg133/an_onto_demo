//! # 为什么修法不是「把语料扩得足够大」
//!
//! 那是追枚举尾巴：REQ-066 已经确认**有限枚举不可能穷尽**
//! （闸门只要是可被独立改写的函数体，就必然存在「与全部钉一致、但判错」的谓词）。
//! **语料扩大只能提高成本，不能封堵。**
//!
//! 本条的做法是**两个机制，一个也不靠枚举**：
//!
//! | # | 机制 | 位置 | 性质 |
//! | --- | --- | --- | --- |
//! | ① | **载荷封条** [`seal_evidence_line`] | 生产侧 `src/domain/review_view.rs` | 行为层：对**每一个** `Value` 成立，语料在不在无关 |
//! | ② | **结构守卫**（本文件） | 测试层 · 源码文本探针 | 检测层：**不碰任何形状**，断言「出口只有一条」 |
