/// 【AC-001】**每个**退化标签都带得下该元素的载荷 —— 含语料外的形状。
///
/// # 与 REQ-065 那条的关系：**并存，不取代**
///
/// REQ-065 的判据认的是「语料里那批形状的完整载荷」；
/// 本条认的是「**一条规则对所有形状都成立**」——
/// 它问的不是「这个形状的载荷在不在」，而是
/// **「带定界符的行 ⇒ 定界符之间带得下载荷指纹」这条蕴含关系有没有破**。
///
/// # 前提自检（不许省）
///
/// 「语料外的形状确实落在语料外」是本条全部意义所在 ——
/// 若 [`shapes`] 其实全被 REQ-065 收走了，本条就退化成 REQ-065 的复读。
#[test]
fn test_req070_degenerate_label_carries_payload_regardless_of_corpus() {
    // C5 的触发形状 —— 必须**确实不在** REQ-065 的语料里。
    let outside = json!({"a": {"b": {}}});
    let req065_corpus_hit = [
        json!([{"a": {"b": null}}]),   // REQ-065 有这个数组形态
        json!({"table":{}, "column":[]}), // REQ-065 的「近似/值是空容器」
    ];
    let line = rendered_line(&outside);
    for hit in &req065_corpus_hit {
        assert_ne!(
            rendered_line(hit),
            line,
            "前提：`{outside}` 渲染成了 REQ-065 语料里某个形状的行 ⇒ \
             「语料外」这个前提不成立，本条在复读 REQ-065"
        );
    }

    // 那就老老实实走一遍两条规则。
    let mut missing: Vec<String> = Vec::new();
    let mut degenerate_seen = 0usize;
    let mut unmarked_seen = 0usize;

    for (name, ev) in shapes() {
        let line = rendered_line(&ev);
        if !is_degenerate_line(&line) {
            unmarked_seen += 1;
            continue;
        }
        degenerate_seen += 1;
        let want = expected_fingerprint(&ev);
        // 规范空形「无可藏」：类别名已经把它说尽（与 REQ-065 同一口径）。
        if has_nothing_to_hide(&ev) || line.contains(&want) {
            continue;
        }
        missing.push(format!("[{name}] {line:?} 里看不见载荷 {want:?}"));
    }

    // 前提自检：两头都得踩到，否则上面可能在一条空跑的路上全绿。
    //
    // # ⚠️ 为什么门槛留这么大的余量（别把它调高）
    //
    // 变异会改变某个形状**落在哪一侧**（QA 的 C5 给一批对象形状新增了退化类别）。
    // 门槛卡太紧 ⇒ 一次**无害的分类变动**就能让这条**前提自检**变红，
    // 而它红得**与本条的不变量无关** —— 那是**假阳性**，不是判据在开火。
    //
    // 实测过这个余量是怎么被吃掉的：
    //
    // | 门槛 | 基线非退化 | C5 之下 | 结论 |
    // | --- | --- | --- | --- |
    // | `>= 5` | 14 | 10 | 过（但余量已经很薄） |
    // | `>= 10` | 14 | **10**（正好压在门槛上） | 余量 **0** —— 再多一个翻面形状就复发同类假阳性 |
    // | `>= 6` | 14 | 10 | 余量 **4** ✅ |
    //
    // ⇒ 定在 **`>= 6`**。这条自检的职责是「判据**有没有被真正考验**」，
    // 不是「覆盖面够不够宽」—— 覆盖面是 §1 封条的事，不是这条断言的事。
    assert!(
        degenerate_seen >= 8 && unmarked_seen >= 6,
        "前提不足：退化 {degenerate_seen} / 非退化 {unmarked_seen} —— \
         覆盖面不够，判据可能在空跑"
    );
    assert!(
        missing.is_empty(),
        "退化标签藏起了原始载荷（不分语料内外）：\n{}",
        missing.join("\n")
    );
}

/// 【AC-002】补载荷**永远补在定界符之内** —— 补完仍然是退化标签。
///
/// # 为什么不能只数「定界符有两个」
///
/// 封条若把载荷**追加在结尾定界符之后**（`␀嵌套对象␀ {"a":{"b":{}}}`），
/// 定界符**仍然是两个** —— 只数个数照样绿。
/// 但那一行**不再以定界符结尾** ⇒ [`evidence_line_carries_data`] 会把它判成
/// 「携带可复核依据」⇒ REQ-058 的判决翻了。
///
/// ⇒ 这里问的是「载荷落在**最后一枚定界符之前**吗」，
/// 那才是「补完仍然是退化标签」的可执行说法。
#[test]
fn test_req070_sealing_never_breaks_the_degenerate_mark_structure() {
    let mut checked = 0usize;
    for (name, ev) in shapes() {
        let line = rendered_line(&ev);
        if !is_degenerate_line(&line) {
            continue;
        }
        if has_nothing_to_hide(&ev) {
            continue;
        }
        // 定界符**成对**。
        assert_eq!(
            line.chars().filter(|c| *c == DEGENERATE_EVIDENCE_MARK).count(),
            2,
            "[{name}] 保留定界符不是成对的两个：{line:?}"
        );
        // ⚠️ 载荷必须在**最后一枚定界符之前** —— 追加在后面就等于把
        // 这一行从「退化标签」降级成了「普通内容行」，REQ-058 的判决会跟着翻。
        let without_tail = line
            .strip_suffix(DEGENERATE_EVIDENCE_MARK)
            .unwrap_or_else(|| panic!("[{name}] 行不以定界符结尾：{line:?}"));
        assert!(
            without_tail.contains(&expected_fingerprint(&ev)),
            "[{name}] 载荷被补在了**结尾定界符之后** ⇒ 这一行不再被 evidence_line_carries_data 判成退化：\n{line:?}"
        );
        checked += 1;
    }
    assert!(
        checked >= 8,
        "只检查了 {checked} 条带载荷的退化行 ⇒ 覆盖面不足"
    );
}

/// JSON 的四个**规范空形**（测试侧独立复刻，与 REQ-065 同口径）。
fn has_nothing_to_hide(v: &Value) -> bool {
    match v {
        Value::Null => true,
        Value::String(s) => s.is_empty(),
        Value::Array(a) => a.is_empty(),
        Value::Object(o) => o.is_empty(),
        _ => false,
    }
}

