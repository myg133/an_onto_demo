/// 【REQ-077 · AC-001 的入口】**一次渲染一整个 `evidence` 数组**，逐条取回结果。
///
/// # ⚠️ 为什么必须有它，而不能沿用 [`rendered_line`]
///
/// [`rendered_line`] 每次只喂**一条** evidence ⇒ 「封条只对**第 1 条**生效
/// （后两条不过封条）」这一类变异**完全不可观测**：
/// 每条证据都被单独渲染成单项，索引永远是 0，封条**条条都过**。
/// ⇒ 那条变异在九个测试二进制里**全绿**（QA 的 **M2prime2**，192/0）。
///
/// # 为什么它**不需要改生产签名**
///
/// [`rendered_line`] 是**测试侧**的包装器，生产侧 [`payload_evidence`] 一直就是
/// 对 `payload["evidence"]` 整个数组**逐个元素**过封条（`arr.iter().map(...)`）。
/// ⇒ **多条**的渲染路径本来就存在，只是测试一直没用它。
/// 本函数只是把已有的那条路径接出来（见 [`evidence_item`]），
/// **生产代码、公开签名、字段集合一个字都没改**。
fn rendered_lines(evs: &[Value]) -> Vec<String> {
    let v =
        project_review_track_with_summary(&[evidence_item(evs.to_vec())], &BTreeSet::new()).0;
    assert_eq!(
        v.items[0].model.evidence.len(),
        evs.len(),
        "喂进去 {n} 条证据、渲染出来 {m} 条（n={n}）⇒ 证据元素被静默丢掉了 —— \
         「丢掉 = FDE 少一条复核依据，却看不出来」",
        n = evs.len(),
        m = v.items[0].model.evidence.len(),
    );
    v.items[0].model.evidence.clone()
}

/// 单条 —— **既有判据的入口，逐字不变**（薄薄一层，委托给 [`rendered_lines`]）。
///
/// ⚠️ 它之所以还能站在那儿，是因为本文件所有既有判据问的都是
/// 「**这一条**渲染出来带没带载荷」；「**这一条**在数组里的位置对不对」
/// 是 REQ-077 新增那条判据的事。
fn rendered_line(ev: &Value) -> String {
    let mut lines = rendered_lines(std::slice::from_ref(ev));
    lines
        .pop()
        .unwrap_or_else(|| unreachable!("`rendered_lines` 已断言条数一致，喂 1 条必有 1 行"))
}

