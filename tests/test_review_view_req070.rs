/// 本文件的形状族。
///
/// # 它**不是** REQ-065 的语料，也不试图覆盖 REQ-065 的语料
///
/// AC-001 要的是「保护不依赖形状在不在我的语料里」。若本文件也用一份
/// 「已知的形状清单」，那它自己就掉回同一个坑了 —— 所以这里**生成**：
/// 退化 / 非退化 / 嵌套 / 键名网格 / 值形态各铺一层，
/// 并**刻意**包含 REQ-065 语料里**没有**的形状（如 `{"a":{"b":{}}}`，
/// 正是 QA 的 C5 用的那个）。
///
/// ⚠️ **它仍然是一份有限的枚举** —— 本条的保证**不在**它身上，
/// 它只是「封条在消费侧确实接住了输出」的一次**行为取证**。
/// 无枚举的那一半是 [`seal_evidence_line`] 本身（生产代码，见本文件头）。
fn shapes() -> Vec<(&'static str, Value)> {
    let mut out: Vec<(&'static str, Value)> = vec![
        // 规范空形：类别名已经说尽，「无可藏」。
        ("空形/空串", json!("")),
        ("空形/null", json!(null)),
        ("空形/空对象", json!({})),
        ("空形/空数组", json!([])),
        // 退化但**有可带的内容**。
        ("退化/纯空白", json!("  ")),
        ("退化/裸标量", json!(-0.5)),
        ("退化/全退化数组", json!([1, [2]])),
        ("退化/有键无值", json!({"table":"","column":"","claim":""})),
        // **语料外**（不在 REQ-065 的 `corpus()` 里）：QA 的 C5 用的触发形状。
        ("语料外/嵌套对象", json!({"a":{"b":{}}})),
        ("语料外/嵌套两空容器", json!({"outer":{"inner":[]}})),
        ("语料外/中文键", json!({"语义":"", "取值":""})),
        // 非退化：走「按原样呈现」那条路。
        ("非退化/三段式", json!({"table":"t","column":"c","claim":"x"})),
        ("非退化/两段式", json!({"table":"t","column":"c"})),
        ("非退化/只有claim", json!({"claim":"一句话"})),
        ("非退化/值是空容器", json!({"table":{},"column":[]})),
        ("非退化/嵌套带值", json!([{"a":{"b":null}}])),
        // ⚠️ 非退化这一层铺得**比退化层厚**，是故意的：
        // 变异会改变某个形状**落在哪一侧**（QA 的 C5 就是给两个形状
        // 新增了一个退化类别）。若两侧都铺得刚好够，两侧的比例一被改动，
        // 下面那条**前提自检**就会先于正题变红 —— 那是**假阳性**，
        // 不是判据在开火。非退化层留足余量，前提自检才只反映
        // 「判据有没有被真正考验」。
        ("非退化/裸真字符串", json!("一句真实的话")),
        ("非退化/数字数组", json!([1, 2, 3])),
        ("非退化/布尔", json!(true)),
        ("非退化/带值的普通对象", json!({"other":"x"})),
        ("非退化/键不是三段式", json!({"semantic":"has","table":"t"})),
        ("非退化/数组混真证据", json!([1,"真证据"])),
        ("非退化/深嵌套带值", json!({"a":{"b":{"c":"d"}}})),
        ("非退化/值带换行", json!({"k":"a\nb"})),
        ("非退化/多值对象", json!({"a":"1","b":"2","c":"3"})),
    ];
    // 键名网格：键不同 ⇒ 问题性质不同，渲染必须分得开。
    for (name, keys) in [
        ("键网格/单键", vec!["只有键"]),
        ("键网格/多键", vec!["a", "b", "c"]),
        ("键网格/含定界符", vec!["\u{2400}k", "b"]),
    ] {
        let mut o = serde_json::Map::new();
        for (i, k) in keys.iter().enumerate() {
            o.insert(
                (*k).to_string(),
                if i % 2 == 0 {
                    json!("")
                } else {
                    Value::Null
                },
            );
        }
        out.push((name, Value::Object(o)));
    }
    out
}

/// 这个 payload 在渲染结果里**应该**看得见的那个字符串（测试侧独立复刻）。
fn expected_fingerprint(v: &Value) -> String {
    v.to_string().replace(DEGENERATE_EVIDENCE_MARK, &MARK_ESCAPE.to_string())
}

fn is_degenerate_line(line: &str) -> bool {
    line.chars().count() > 1
        && line.starts_with(DEGENERATE_EVIDENCE_MARK)
        && line.ends_with(DEGENERATE_EVIDENCE_MARK)
}

