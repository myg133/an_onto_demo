    let mut grid: Vec<(&'static str, Value)> = shapes();
    grid.extend(witnesses.iter().map(|(n, v, _)| (*n, v.clone())));
    let (findings, checked) = seal_findings(&grid, &|_, ev| rendered_line(ev));

    // 前提自检 ③：不是空跑。门槛定得很松是**故意的** ——
    // 这条只管「判据有没有被真正跑过」，不管覆盖面（覆盖面是见证形状那一节的事）。
    assert!(
        checked >= 20,
        "只核对了 {checked} 个取值 ⇒ 判据可能在空跑（基线是 29 个：28 个语料扣掉 5 个「无可藏」\
         的，再加 6 个见证形状）"
    );
    assert!(
        findings.is_empty(),
        "渲染结果把载荷**整个藏起来**了（不看源码、不看语料内外）：\n{}",
        findings.join("\n")
    );

    // ⚠️ 前提自检 ④：**判据必须能红**（自检变异 = 喂「不过封条的那一行」）。
    //
    // 照 QA 的 SEALGAP3 的形状：把影子渲染器注入同一个判据，要求它**报出东西**。
