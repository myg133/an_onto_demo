/// 生产 `escape_payload_text` 里那两个换行转义（测试侧独立复刻，不 import 私有常量）。
const LINE_FEED_ESCAPE: char = '\u{240A}';
const CARRIAGE_RETURN_ESCAPE: char = '\u{240D}';

/// 测试侧独立复刻的转义 —— **只**认生产那三个字符。
///
/// ⚠️ 与生产 [`escape_payload_text`] 是两份实现：这一份是**见证形状的预言**用的，
/// 问的是「渲染器不过封条时会算出什么」。生产改了转义表 ⇒ 前提自检先报红，
/// 而不是让正题报一个看不懂的红（与 REQ-075 同一取舍：**宁可假红，不可恒真**）。
fn escape_like_production(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            DEGENERATE_EVIDENCE_MARK => MARK_ESCAPE,
            '\n' => LINE_FEED_ESCAPE,
            '\r' => CARRIAGE_RETURN_ESCAPE,
            other => other,
        })
        .collect()
}

/// 测试侧独立复刻的**载荷原子** —— 生产 `payload_atoms` 的定义：
/// 对象的**键名** + 全部**非空叶子标量**（非纯空白字符串 / 数字 / 布尔）的字面文本。
///
/// ⚠️ 与生产是两份实现，这是**故意的**：判据的期望值不能向被测物要答案。
/// 代价见本文件模块注释的「假阳性面」一节。
fn payload_atoms_of(v: &Value) -> Vec<String> {
    fn walk(v: &Value, out: &mut Vec<String>) {
        match v {
            Value::Object(o) => {
                for (k, val) in o {
                    out.push(k.clone());
                    walk(val, out);
                }
            }
            Value::Array(a) => a.iter().for_each(|e| walk(e, out)),
            Value::String(s) => {
                if !s.trim().is_empty() {
                    out.push(s.clone());
                }
            }
            Value::Number(_) | Value::Bool(_) => out.push(v.to_string()),
            Value::Null => {}
        }
    }
    let mut out = Vec::new();
    walk(v, &mut out);
    out
}

/// **见证形状**：(名字, 取值, 「渲染器不过封条时会算出的那一行」)。
///
/// # 为什么第三项能被**独立地**算出来
///
/// 这不是「把渲染器再抄一遍」——见证形状是**按 `evidence_object_body` 的行为挑的**：
/// `table` / `column` 都缺省、只有 `claim` 有值时，那个函数**逐字**返回 `claim` 的值，
/// 而 [`render_evidence_entry`] 随后把它交给转义。于是「不过封条的那一行」
/// = 转义后的 `claim`，**一行算得出来**。
/// ⚠️ 「`table` / `column` 都缺省」这条前提由测试里的前提自检 ① 逐条核对：
/// 生产若改了取用规则，先报红的是前提自检。
///
/// # 为什么必须有见证形状（否则本条恒真）
///
/// 封条规则①（带定界符 ⇒ 载荷在定界符之内）在基线上**从不触发** ——
/// 标签本来就带指纹。可判别的是**规则②**（自称「按原样呈现」却一个载荷原子都不带
/// ⇒ 重新按原样呈现紧凑 JSON）。
/// 而规则②在基线上要开火，渲染器得先算出一行**一个原子都不带**的话。
/// 三段式摘要**只吐取值、不吐键名**，所以：只要取值里带一个**会被转义的字符**
/// （`␊` / `␍` / `␀`），那一行就既不含键名、也不含原样的取值 ⇒ 规则②开火。
///
/// # ⚠️ 这**不是**一张穷尽的网格（REQ-077 · AC-002，原文是「这就是见证形状的全部来由：
/// 一个网格，不是三个手挑的巧合」—— 那半句是**过度声明**，本条改掉）
///
/// 「3 转义字符 × 2 形态 = 6」**只在「转义表」这一轴上**是真网格，
/// 而且**两个形态走的是同一条渲染分支**（`body` 都只由 `claim` 决定），
/// 第二形态只是把载荷加厚，**不产生第二种取用路径**。
///
/// QA 静态推出**至少 5 种**可达且承重的形态**不在**这份网格里
/// （空白 table/column 被 `present()` 滤掉后的形态 / table+claim 双转义 /
/// 双转义且无 claim / **键名本身**带转义字符走紧凑 JSON 兜底 / 非对象数组）。
/// ⇒ 「见证集合会随取用规则的变化自行再生」这半句**不成立**。
///
/// # 那为什么不做成穷举网格
///
/// **因为判据只需要「至少一个承重见证」。** REQ-066 已经证明有限枚举不可穷尽，
/// 追这条尾巴的成本永远追不上。而**够用**由前提自检保证：
/// ② 逐个强制「每一条都真的不承重就不算数」（失败模式是**假红**，不是恒绿），
/// ④ 再强制判据对影子渲染器**必须能红**。
/// ⇒ 覆盖不足只影响**冗余度**，不影响**牙齿**；文档不得据此声称「穷尽」。
fn seal_witnesses() -> Vec<(&'static str, Value, String)> {
    let mut out = Vec::new();
    for (mangle_name, mangle) in [
        ("换行", '\n'),
        ("回车", '\r'),
        ("定界符", DEGENERATE_EVIDENCE_MARK),
    ] {
        // 形态一：只有 claim。渲染器取得到的全部内容就是那个被转义过的取值。
        let c1 = format!("载荷{mangle}藏起来了");
        out.push((
            "见证/claim带转义字符",
            json!({ "claim": c1 }),
            escape_like_production(&c1),
        ));
        // 形态二：再多一个与三段式无关的键。渲染器**取不到**它（它不在键名网格里），
        // 封条却必须把它带回来 ⇒ 原子更多、封条更承重。
        let c2 = format!("另有一个键{mangle}也不见");
        out.push((
            "见证/三段式之外还有键",
            json!({ "a": "这个键渲染器取不到", "claim": c2 }),
            escape_like_production(&c2),
        ));
        let _ = mangle_name;
    }
    out
}

/// 判据本体 —— 「有载荷原子 ⇒ 渲染结果里看得见**至少一个**」。
///
/// # 这句话是哪来的
///
/// 它**就是**封条规则②的可观测效果，一字不改：
/// 规则②要么放行（那时行里本来就有一个原子），要么重新按原样呈现紧凑 JSON
/// （紧凑 JSON 带全键名 ⇒ 带得上原子）。
/// ⇒ 「封条在链上」⇒ 判据恒成立；「封条被摘掉 / 被影子函数吃掉」⇒ 判据在见证形状上报红。
///
/// - `atoms(v)` 为空的取值（JSON 的规范空形 + 纯空白串）**跳过**：
///   那一类「无可藏」，封条规则②对它**不承诺任何东西**，判据也不该凭空要求。
/// - `line_of` 是**注入**的：真实运行传生产管线，自检变异传「不过封条的那一行」
///   —— 真值因此依赖被注入的东西，不是 `assert!("ab".contains("ab"))` 那种空断言。
fn seal_findings<F>(grid: &[(&'static str, Value)], line_of: &F) -> (Vec<String>, usize)
where
    F: Fn(&'static str, &Value) -> String,
{
    let mut findings = Vec::new();
    let mut checked = 0usize;
    for (name, ev) in grid {
        let atoms = payload_atoms_of(ev);
        if atoms.is_empty() {
            continue;
        }
        checked += 1;
        let line = line_of(name, ev);
        if !atoms.iter().any(|a| line.contains(a.as_str())) {
            findings.push(format!(
                "[{name}] 渲染结果 {line:?} 里一个载荷原子都看不见（该有 {atoms:?}）\
                 ⇒ 这一行的载荷是被藏起来的，封条没有生效"
            ));
        }
    }
    (findings, checked)
}

/// 【REQ-076 · AC-001 · M1/M3 的杀手】封条**接在**渲染链上 —— **由行为判定**。
///
/// # REQ-076：这一格原来是一句**字面量探针**
///
/// REQ-075 的 QA 实测（`SEALGAP3`）：在 [`payload_evidence`] 的函数体里留一行
/// `let _decoy = seal_evidence_line;` 当诱饵，真正的调用改走一个**不过封条**的影子函数
/// ⇒ 字面量在、接线没了，而 **req070 7/0 全绿**，全仓 118/0 无感。
