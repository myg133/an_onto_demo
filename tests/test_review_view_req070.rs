    for (name, ev, unsealed) in &witnesses {
        let line = rendered_line(ev);
        assert_ne!(
            line, *unsealed,
            "封条**没有生效**：见证形状 {name} 的渲染结果 {line:?} 与「渲染器不过封条时会算出的那一行」\
             逐字相同 ⇒ 载荷在渲染结果里一个原子都看不见（该有 {:?}），而封条没有把它改回来。\n\
             ⇒ 这一格要么封条被摘掉了（`payload_evidence` 不再过封条），\
             要么它被一个不过封条的影子函数顶替了（哪怕源码里还留着封条的**字面量**）。",
            payload_atoms_of(ev)
        );
        assert_eq!(
            line,
            escape_like_production(&ev.to_string()),
            "见证形状 {name} 的渲染结果 {line:?} 不是「封条规则②修复之后」的形态\
             （转义后的紧凑 JSON）⇒ 生产侧规则②的行为变了，先确认生产意图，再决定要不要改判据"
        );
    }

    // ═══ 正题 B：这一份**取值集合**（本文件语料 + 见证形状）逐个过判据 ═════
    //
    // ⚠️ REQ-077 · AC-002：原文写的是「**全网格**」—— **过度声明**。
    // 这一份集合**不是**承重形态的穷举（`seal_witnesses()` 的文档已把理由写全），
