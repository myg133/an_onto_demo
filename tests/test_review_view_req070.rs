/// 扫描网的主体 —— 返回**问题清单**（空 = 通过）与**实际核对过的配对数**。
///
/// # 为什么 `label_of` 是**注入**的
///
/// 真实运行传生产的 [`evidence_degeneracy_labels`]；自检变异传一个「影子版本」。
/// 判据的**真值因此依赖注入的东西**，而不是 `assert!("ab".contains("ab"))` 那种
/// 与被测物无关的空断言 —— 本项目栽过好几次的那种坑。
///
/// # 核对的是哪一句话
///
/// 「**每一个**退化类别 × **每一个**带载荷的取值 ⇒ `label()` 的输出里
/// 带得下该元素的完整载荷」。
///
/// - **类别轴是穷举的**（生产侧 [`evidence_degeneracy_labels`] 遍历
///   [`EvidenceDegeneracy::ALL`]）⇒ 新增类别自动进网；
/// - **取值轴是一份有限语料**（[`shapes`]）⇒ ⚠️ 这一格**没有**脱离语料，
///   与 REQ-070 原样，**如实登记**在本文件模块注释的边界表里。
fn label_sweep_findings<F>(grid: &[(&'static str, Value)], label_of: &F) -> (Vec<String>, usize)
where
    F: Fn(&Value) -> Vec<(&'static str, String)>,
{
    let mut findings = Vec::new();
    let mut checked = 0usize;
    for (name, ev) in grid {
        // 规范空形「无可藏」：JSON 规范本身只有四种（`""` / `null` / `{}` / `[]`），
        // 类别名已经把它说尽了 —— 这是 **JSON 的事实**，不是生产实现的一份复刻。
        if has_nothing_to_hide(ev) {
            continue;
        }
        let want = ev.to_string();
        for (cat, label) in label_of(ev) {
            checked += 1;
            if !label.contains(&want) {
                findings.push(format!(
                    "[{name}] 类别 {cat:?} 的标签 {label:?} 里看不见载荷 {want:?}"
                ));
            }
        }
    }
    (findings, checked)
}

/// 【REQ-075 · AC-002 · M3/M9 的杀手】**每一个**退化类别的标签都带得下那个元素的载荷。
///
/// # 它取代了什么
///
/// 原先的判别力挂在 `body.contains("if fingerprint.is_empty() {")` 这个**字面量**上。
/// QA 的 **M9** 用「影子变量改指纹 + **逐字保留该字面量**」就让 **req070 全绿 6/0**
/// ⇒ 那条断言证明不了任何事，它只是「长得像判据」。
///
/// 本条**一个源码字面量都不读**：它调用生产的
/// [`evidence_degeneracy_labels`] → 生产的 [`EvidenceDegeneracy::label`]。
///
/// # 所以它能杀什么（**都是**改变了 `label()` 输出的写法）
///
/// | 写法 | 旧守卫 | 本条 |
/// | --- | --- | --- |
/// | C5：`return self.category()` | 🔴 | 🔴 |
/// | M9：影子变量换掉指纹、**逐字保留字面量** | 🟢 **假绿** | 🔴 |
/// | 别名 / 中间变量 / 把拼装挪进 `category()` | 🟢 | 🔴 |
///
/// ⚠️ 它**只**对 `label()` 的**输出**有牙。改的是别的环节（渲染器不调 `label()`）
/// 它一声不吭 —— 那格由 [`seal_evidence_line`] 与调用点计数守卫负责。
#[test]
fn test_req070_every_degeneracy_label_carries_the_payload_of_its_value() {
    let grid = shapes();

    // ⚠️ **前提自检 ①：扫描轴与生产分类器必须对得上**（不许省）。
    //
    // 这条**专门堵「扫描网悄悄少扫了一半」** —— 那正是 REQ-073 刚挖出来的形状
    // （「守卫的一部分静默跳过，而守卫报绿」）。两个方向都要堵：
    //
    // | 对不上 | 含义 |
    // | --- | --- |
    // | 只有扫描轴有 | 有类别没被任何形状够到 ⇒ 扫了也白扫 |
    // | 只有分类器有 | 有类别**没登记进** `ALL` ⇒ 生产能产出它，扫描网却盖不到 |
    assert!(
        !evidence_degeneracy_labels(&json!({})).is_empty(),
        "扫描轴（`EvidenceDegeneracy::ALL`）是空的 ⇒ 下面那次扫描可能在一条空跑的路上全绿"
    );
    let axis: BTreeSet<&str> = evidence_degeneracy_labels(&json!({}))
        .into_iter()
        .map(|(cat, _label)| cat)
        .collect();
    let reachable: BTreeSet<&str> = grid
        .iter()
        .filter_map(|(_, ev)| evidence_degeneracy_category(ev))
        .collect();
    assert_eq!(
        axis, reachable,
        "扫描轴与生产分类器对不上 ⇒ 扫描网**漏扫**或**空扫**：\n\
         扫描轴有、生产走不到：{axis:?}\n\
         生产走得到、扫描轴没有：{reachable:?}\n\
         ⚠️ 新增退化类别后**必须**同时：① 登记进 `EvidenceDegeneracy::ALL`，\
         ② 在 `shapes()` 里放一个能被它判出来的取值 —— 两件事都会被这条逼出来。"
    );

    // ── 正题：真实生产实现 ──────────────────────────────────
    let (findings, checked) = label_sweep_findings(&grid, &evidence_degeneracy_labels);

    // 前提自检 ②：核对的配对数不能是一条「什么都没跑」的路。
    //
    // ⚠️ 门槛定得很松（`8 × 8`）是**故意的**：
    // 实测基线是 8 类 × 24 个带载荷形状（`shapes()` 的 28 个里扣掉四个规范空形）
    // = **192** 对。
    // 这条自检只负责「不是空跑」，**不负责**覆盖面宽窄 —— 覆盖面是前提自检 ① 的事。
    assert!(
        checked >= 8 * 8,
        "只核对了 {checked} 对（类别 × 形状）⇒ 扫描网可能在空跑"
    );
    assert!(
        findings.is_empty(),
        "有退化类别的标签藏起了原始载荷（不看语料内外、不看怎么写的）：\n{}",
        findings.join("\n")
    );

    // ⚠️⚠️ **前提自检 ③：扫描网必须真的能红**（自检变异 = QA 的 M9）。
    //
    // 照 M9 的形状注入一个影子版本：**类别名还在、载荷没了**，
    // 而生产侧 `if fingerprint.is_empty() {` 那个字面量一个字都没动
    // —— M9 证明过那正是旧守卫全绿的原因。
    //
    // 若本条对影子版本无感，它就是**恒真**：看上去有防护，实际没有。
    let shadow = |v: &Value| -> Vec<(&'static str, String)> {
        let mut labels = evidence_degeneracy_labels(v);
        if let Some(last) = labels.last_mut() {
            last.1 = last.0.to_string();
        }
        labels
    };
    let (mutant, mutant_checked) = label_sweep_findings(&grid, &shadow);
    assert!(
        mutant_checked > 0,
        "自检变异一条都没核对 ⇒ 扫描网压根没跑起来（先修扫描网，别谈它能不能红）"
    );
    assert!(
        !mutant.is_empty(),
        "扫描网杀不掉 M9（影子变量把某个类别的载荷吃掉、生产字面量逐字保留）⇒ 它恒为真：\n\
         这与 QA 在 REQ-073 判过的「守卫无防护却报绿」是同一种病"
    );
}

/// 【AC-003 · M2 的杀手】退化判据**之前**没有任何 `return`。
