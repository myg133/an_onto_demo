//! REQ-093 · **只读** HTTP 服务（把本体图关系摆到浏览器里）。
//!
//! # 为什么不放在 `domain/`
//!
//! 与 `mcp/` / `agent/` 同一条理由（见 `src/lib.rs`）：它要连库、要起 socket，
//! 而 `domain/` 的判据（口径见 `domain/mod.rs` 的模块头）是**剥掉注释后零命中**。
//! 这一层**就是那个对照面**。
//!
//! # 只读是三件事同时成立，不是一句口号
//!
//! 1. **路由层**：只注册 `GET`；任何变更动词 ⇒ 405（且**正文必须有人话**）。
//! 2. **接线层**：`server/` 里不引用任何写本体的函数
//!    （提案 / 裁决 / apply / freeze 一律不经过这里）。
//! 3. **身份层**：无令牌 ⇒ 401，**没有开关能绕过**。
//!
//! # ⛔「只读」的**准确**表述：「HTTP 暴露面只读」，**不是**「这个进程只读」
//!
//! `cli.rs::run` 对**所有**子命令**无条件**跑 `migrate()` —— 那是 DDL +
//! 回填 `UPDATE`。所以 `ontok serve` 这个**进程启动时仍然需要库写权限**
//! （基线既有行为，本需求未改它）。
//!
//! 也就是说：HTTP **暴露面**上没有任何能改动本体的入口（这是真的，见下），
//! 但进程本身并不是只读的。**别让下一个人以为它不需要写权限** ——
//! 真要做到「进程只读」，得把 `migrate` 从只读子命令里摘出去，那是另一条需求。
//!
//! # 已知限制 · P2 · **守卫强度不足，未封堵**（纪律 H）
//!
//! ⚠️ **不得读成「已封堵」。** QA 的变异实验证明：
//!
//! - `server_has_no_write_path_to_the_ontology` 是**拼写黑名单**，不是语义判据。
//!   把一条真实的 `delete from snapshots` 改写成 `query_scalar` + 小写，
//!   **全绿放行** —— 连既有的 `test_no_write_path` / `test_read_only_guard`
//!   也一并放行。**判据认的是那几个词的拼写，不是「这是一条写语句」。**
//! - **节点侧只有字符串匹配**：静默丢节点（边数 79 → 42、HTTP 200）
//!   没有任何测试会红。边侧有 `no_edge_is_ever_dropped_for_a_projected_view`
//!   钉着不变量，但那条用的是**合成快照**，抓不到只在真实数据上才显现的改动。
//!
//! ⛔ **但产品结论本身是真的**，且**不靠那条测试** —— QA 是靠**独立读代码**
//! 得出的：`src/server/` 对存储层只有 `PgProjectStore` / `PgStore` 两个 `use`，
//! 调用只有 `get_by_name` / `version_by_seq` / `get_snapshot` 三个方法，
//! 没有任何提案 / 审核 / apply / freeze 入口。
//!
//! ⇒ 这是**守卫不够强**，不是**产品有洞**。加固另立需求跟踪，本轮不修。
//!
//! # 已修 · REQ-104 · demo3 第 2 版有 3 个节点点不开（曾登记为 P1 遗留）
//!
//! **原现象**：逐个核对 91 个节点时实测，`鉴权缓存变更事件` / `鉴权缓存消息事件` /
//! `用量明细` 的 `/api/node` 返回 **HTTP 500**，因为它们**属性文案里带建模黑话**
//! （`稳定来源事件ID：CDC/table/op/pk/lsn…`、`Kafka key；单 key 事件…`）。
//! 守门器**正确拒发**了 —— 它该做的做到了。
//!
//! # ⚠️ 本条旧注记的前提已被证伪（REQ-104 裁定）
//!
//! 旧注记写的是「正确的修法在**数据侧**（改属性文案 / 补翻译），属另一条需求」。
//! **那条路修不了已冻结的 v2** —— `get_snapshot` 从版本表读**已冻结**的快照，
//! 改抽取层（`extract::propose`）只影响**未来**抽取出来的版本。
//! 要让数据侧生效得重新抽取并冻结成 v3，而用户点不开的是**当前部署的 v2**。
//!
//! # 实际修法：出口层属性级剔除（第四条路）
//!
//! 同一份数据在**页面出口**上本来就过得去（`ontology show --html` exit 0，
//! stderr 报「有 N 条属性带技术用语，没上页面」）—— `html_view` 早就有一道属性级清洗，
//! 只是**另外三个出口没有**。REQ-104 把那道已有的判据
//! （`domain::identifier_shape::has_raw_identifier`，全仓一份）接到
//! **JSON 出口 / `/api/node` / MCP** 三个出口上，调 [`crate::domain::property_filter`]。
//!
//! ⛔ **守门器 `guard()` 一行没改** —— 那半句原则仍然成立，而且现在指的是
//! **不许改 `guard()` 本身**：本轮做的是在它**之前**减掉属性，不是放宽它的判据。
//! 真·建模术语（`主键` / `基数` / `1:N`）不是标识符形态，剔不掉，照旧被拒。
//!
//! ⛔ 两种口径的差异**原样保留**：`/api/node` 仍是**逐节点**判，
//! `ontology show`（JSON）仍是**整份** fail-closed。
//!
//! ⛔ **遗留的已知限制**：`tests/drop_rate` 门禁调的是 `view::project()`，
//! 而剔除在其**之后** ⇒ 那约 20 条客户可见损失**不再被该门禁测量**。
//! 登记与重新评估条件见 [`crate::domain::property_filter`] 模块头（纪律 H：登记，未封堵）。
//!
//! # 已知限制 · 日志里会出现 `mcp-server` 字样（REQ-093 复用守门器的副作用）
//!
//! 本模块**复用** `mcp::tools::guard`（不抄判据 —— 纪律 H），而那个函数里
//! **硬编码**了前缀：
//!
//! ```text
//! ✗ mcp-server 守门器命中 N 项建模术语，已拒绝外送：…
//! ```
//!
//! ⇒ 命中时**只读图服务**的 stderr 也会打这一行。排障的人看到 `mcp-server`
//! 会以为起的是 MCP 服务而不是 HTTP 服务 —— **日志与事实不符**。
//!
//! **影响面**：仅限**守门器命中时**的一行 stderr；HTTP 响应体不含该前缀
//! （`guard` 返回的是不含词条的通用文案）。
//!
//! **为什么本轮不改**：`mcp/tools.rs` **超范围**，且它同时服务 MCP 通道，
//! 改前缀要连带改它的调用方与既有断言。
//!
//! **触发条件 / 何时修**：当出现第二个调用方（本需求已经是第二个）后，
//! 把前缀改成**调用方自报**（例如给 `guard` 加一个 `channel: &str` 参数）。
//! 登记为**已知限制，未封堵**。
//!
//! # ⚠️ 纪律级事实 · 源码扫描型守卫的「变异二进制 sha256」**不构成证据**
//!
//! QA 的变异 B1 与 B2 里，**测试二进制 sha256 完全相同**，因为
//! `read_source` 是**运行时读工作区文件**、不是编译进二进制的 ——
//! 变异只改工作区，二进制当然不变。
//!
//! ⇒ 给这类守卫取变异证据，要取的是**被扫文件的工作区 sha256**，
//! 不是二进制 sha256。否则「二进制没变」会被误读成「测试没跑过变异」。
//!
//! # ⚠️ 纪律级事实 · `--help` 里写「安静地什么都不返回」是**实测为假**的陈述
//!
//! 文档不是许愿池。原先 `--help` 写「参数缺了会安静地什么都拿不到
//! （不报错，只是空）」，实测 clap 是 **exit 2 直接报错**，而同一篇文档
//! 下一段又自相矛盾说会给 400。**已按实测改写。**
//! 由此立一条通用口径：**参数错误与路径错误都必须说话，不许静默。**
//!
//! # 选型：axum 0.7（理由见 `http.rs` 模块头）
//!
//! # 已知限制 · L5：**暂不拆成独立进程**（BA 已裁定）
//!
//! 评审提过「HTTP 服务该不该独立进程」。**结论：留在本 crate**，与
//! `mcp-server` 同构 —— 一个二进制、一次构建、同一份守门器与投影。
//!
//! - **拆出去会失去什么**：要么复制一份守门器判据（纪律 H：两份永远一致，
//!   于是永远绿、也永远可能悄悄不同），要么把 `CustomerView` 的 JSON 变成
//!   跨进程契约（那份 JSON **今天就是拒发的**，见下）——两者都比同进程贵。
//! - **留在同进程的代价**：服务端二进制背着整个抽取/提案工具链的代码与编译体积。
//!   目前可接受，因为 `serve` 只读、只连一个库、只绑回环。
//!
//! **重新评估的触发条件**（写死，免得下一个人重新讨论一遍）：
//! ① 需要**按项目 / 按租户独立部署**（今天一个进程只服务一版，天然单租户）；
//! ② 需要**独立升级服务端**而不动本体内核；
//! ③ 出现**第二个服务端**（例如按租户分片），届时进程边界才开始划得出来。
//!
